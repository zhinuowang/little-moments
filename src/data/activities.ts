export const ACTIVITY_BY_ID: Record<string, Activity> = Object.fromEntries(
  ACTIVITIES.map((a) => [a.id, a]),
)

/** Same activity (same stable id), text in the chosen language. */
export function localizeActivity(a: Activity, lang: Lang): Activity {
  if (lang === 'en') return a
  const zh = ACTIVITIES_ZH[a.id]
  return zh ? { ...a, ...zh } : a
}
